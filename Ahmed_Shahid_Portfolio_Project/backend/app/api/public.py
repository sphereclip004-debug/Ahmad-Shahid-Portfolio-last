router = APIRouter(prefix="/api/public", tags=["public"])
_hits: dict[str, deque[float]] = defaultdict(deque)
_hits_lock = Lock()

def _rate_limit(request: Request, bucket: str, limit: int, window: int = 3600) -> None:
    ip = request.client.host if request.client else "unknown"
    key = f"{bucket}:{ip}"
    now = time.monotonic()
    with _hits_lock:
        q = _hits[key]
        while q and now - q[0] > window:
            q.popleft()
        if len(q) >= limit:
            raise HTTPException(status_code=429, detail="Too many submissions. Please try again later.")
        q.append(now)

def _valid_email(email: str) -> bool:
    email = email.strip()
    return len(email) <= 254 and bool(re.fullmatch(r"[^\s@<>]+@[^\s@<>]+\.[^\s@<>]{2,}", email))

@router.get("/data")
def public_data(db: Session = Depends(get_db)):
    settings = get_setting(db, "site_config", {}) or {}
    result = {}
    kinds = ("education", "skills", "services", "projects", "reviews")
    for kind in kinds:
        items = list_items(db, kind, include_unpublished=False, approved_only=(kind == "reviews"))
        result[kind] = [{"id": x.id, "data": x.data, "sort_order": x.sort_order} for x in items]
    public_setting_fields = {"portfolio_name", "cv_name", "browser_title", "meta_description", "tagline", "intro", "hero_description", "about_text", "footer_text", "contact_email", "whatsapp_number", "location", "profile_image_x", "profile_image_y"}
    result["settings"] = {key: value for key, value in settings.items() if key in public_setting_fields}
    return result

@router.get("/profile-image")
def profile_image(db: Session = Depends(get_db)):
    settings = get_setting(db, "site_config", {}) or {}
    filename = str(settings.get("profile_image_file") or "").strip()
    if filename:
        # Only a basename generated by our upload handler is accepted.
        if filename != __import__("pathlib").Path(filename).name or not re.fullmatch(r"profile-[a-f0-9]{32}\.webp", filename):
            raise HTTPException(status_code=404, detail="Profile image not found.")
        path = UPLOAD_DIR / filename
        if path.is_file():
            return FileResponse(path, media_type="image/webp", headers={"Cache-Control": "no-cache"})
    placeholder = PROJECT_DIR / "frontend" / "assets" / "images" / "profile-placeholder.webp"
    return FileResponse(placeholder, media_type="image/webp", headers={"Cache-Control": "public, max-age=3600"})

@router.get("/media/{filename}")
def public_project_media(filename: str):
    if not re.fullmatch(r"project-[a-f0-9]{32}\.webp", filename):
        raise HTTPException(status_code=404, detail="Image not found.")
    path = UPLOAD_DIR / filename
    if not path.is_file():
        raise HTTPException(status_code=404, detail="Image not found.")
    return FileResponse(path, media_type="image/webp", headers={"Cache-Control": "public, max-age=31536000, immutable", "X-Content-Type-Options": "nosniff"})

@router.get("/cv.pdf")
def download_cv(db: Session = Depends(get_db)):
    settings = get_setting(db, "site_config", {}) or {}
    filename = str(settings.get("cv_uploaded_file") or "").strip()
    if filename and filename == __import__("pathlib").Path(filename).name and re.fullmatch(r"cv-[a-f0-9]{32}\.pdf", filename):
        path = UPLOAD_DIR / filename
        if path.is_file():
            return FileResponse(path, media_type="application/pdf", filename="Ahmed_Chai_CV.pdf", headers={"X-Content-Type-Options": "nosniff"})
    cv = get_setting(db, "cv_content", {}) or {}
    education = db.query(PortfolioItem).filter(PortfolioItem.kind == "education", PortfolioItem.published.is_(True)).order_by(PortfolioItem.sort_order.asc()).all()
    skills = db.query(PortfolioItem).filter(PortfolioItem.kind == "skills", PortfolioItem.published.is_(True)).order_by(PortfolioItem.sort_order.asc()).all()
    projects = db.query(PortfolioItem).filter(PortfolioItem.kind == "projects", PortfolioItem.published.is_(True)).order_by(PortfolioItem.sort_order.asc()).all()
    pdf = generate_cv_pdf(cv, settings, [{"data": x.data} for x in education], [{"data": x.data} for x in skills], [{"data": x.data} for x in projects])
    return Response(content=pdf, media_type="application/pdf", headers={"Content-Disposition": 'attachment; filename="Ahmed_Chai_CV.pdf"', "X-Content-Type-Options": "nosniff", "Cache-Control": "no-store"})

@router.post("/contact")
async def submit_contact(payload: ContactPayload, request: Request, db: Session = Depends(get_db)):
    _rate_limit(request, "contact", 5, 3600)
    if payload.website.strip():  # bots may fill the hidden honeypot
        return {"ok": True, "message": "Your message has been received."}
    name, email, subject, message = payload.name.strip(), payload.email.strip(), payload.subject.strip(), payload.message.strip()
    if not _valid_email(email) or not name or len(message) < 5:
        raise HTTPException(status_code=422, detail="Please provide a valid name, email, and message.")
    record = ContactSubmission(name=name, email=email, subject=subject, message=message, status="unread")
    db.add(record)
    db.commit()
    db.refresh(record)
    await send_event("contact.created", {"id": record.id, "name": name, "email": email, "subject": subject, "message": message}, event_id=f"contact-{record.id}")
    return {"ok": True, "message": "Thanks — your message has been received."}

@router.post("/reviews")
async def submit_review(payload: ReviewPayload, request: Request, db: Session = Depends(get_db)):
    _rate_limit(request, "review", 4, 3600)
    if payload.website.strip():
        return {"ok": True, "message": "Your review was submitted for moderation."}
    name, role, message = payload.name.strip(), payload.role.strip(), payload.message.strip()
    if not name or len(message) < 8:
        raise HTTPException(status_code=422, detail="Please provide your name and a longer review.")
    item = PortfolioItem(kind="reviews", data={"name": name, "role": role, "message": message, "rating": payload.rating}, sort_order=0, published=False, moderation_status="pending")
    db.add(item)
    db.commit()
    db.refresh(item)
    await send_event("review.created", {"id": item.id, "name": name, "role": role, "rating": payload.rating, "message": message}, event_id=f"review-{item.id}")
    return {"ok": True, "message": "Thank you. Your review will appear after approval."}
